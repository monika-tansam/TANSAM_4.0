export function filterTrainingRecords(records, { query = '', year = '', domain = '' } = {}) {
  const search = query.trim().toLowerCase().replace(/\s+/g, ' ');
  return records.filter(record =>
    (!search || record.course.toLowerCase().includes(search)) &&
    (!year || record.year.startsWith(year)) &&
    (!domain || record.domain === domain)
  );
}

export function sumParticipants(records) {
  return records.reduce((total, record) => total + record.count, 0);
}
